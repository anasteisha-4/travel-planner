def load_pairs(db: Session, dest_df: pd.DataFrame, feature_cols: list[str]) -> list[dict]:
    """Load ltr_training_pairs, join with dest features, build feature matrix."""
    logger.info("Loading ltr_training_pairs …")
    rows = db.execute(
        text(
            "SELECT query_id, destination_id, relevance_label, content_score, "
            "profile_snapshot, travel_month "
            "FROM ltr_training_pairs "
            "ORDER BY query_id, relevance_label DESC"
        )
    ).fetchall()
    logger.info("Loaded %d pairs from %d unique queries", len(rows), len(set(str(r.query_id) for r in rows)))

    dest_idx: dict[str, int] = {
        str(row["destination_id"]): int(i)
        for i, row in dest_df.iterrows()  # type: ignore[arg-type]
    }

    records = []
    skipped = 0
    for r in rows:
        dest_id_str = str(r.destination_id)
        if dest_id_str not in dest_idx:
            skipped += 1
            continue
        dest_row = dest_df.iloc[dest_idx[dest_id_str]]

        snapshot = r.profile_snapshot
        if isinstance(snapshot, str):
            snapshot = json.loads(snapshot)
        snapshot = snapshot or {}

        feat = _build_pair_features(snapshot, dest_row, feature_cols, int(r.travel_month))
        records.append(
            {
                "query_id": str(r.query_id),
                "label": int(r.relevance_label),
                "content_score": float(r.content_score),
                "features": feat,
            }
        )

    logger.info("Built %d feature vectors (skipped %d inactive dests)", len(records), skipped)
    return records


