"""LightGBM LambdaRank training script.

Reads from ltr_training_pairs table (generated by generate_ltr_pairs.py).
Each query_id is one synthetic user profile scored against ~100 destinations.

Usage (inside Docker):
    python scripts/train_ranker.py [--holdout 0.2] [--ndcg-cutoff 10]

Pipeline:
  1. Build 39-dim destination feature matrix from DB
  2. Load ltr_training_pairs (query_id, destination_id, relevance_label 0..3)
  3. Build (user-hint × dest) feature vectors per pair
  4. Train LightGBM lambdarank grouped by query_id
  5. Evaluate NDCG@5 and NDCG@10 on held-out queries (not rows)
  6. Save model + metrics to model_registry
"""

