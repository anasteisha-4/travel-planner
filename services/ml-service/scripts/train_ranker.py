def main(holdout: float = 0.20, ndcg_cutoff: int = 10) -> None:
    db_url = os.environ.get("DATABASE_URL", "postgresql://postgres:postgres@localhost:5432/travel_planner")
    engine = create_engine(db_url)
    SessionLocal = sessionmaker(bind=engine)

    with SessionLocal() as db:
        # Check ltr_training_pairs exists and has data
        count = db.execute(text("SELECT COUNT(*) FROM ltr_training_pairs")).scalar()
        if not count:
            logger.error("ltr_training_pairs is empty — run generate_ltr_pairs.py first")
            sys.exit(1)
        logger.info("ltr_training_pairs: %d rows", count)

        logger.info("=== Phase 1: Destination feature matrix ===")
        dest_df = build_destination_feature_matrix(db)
        feature_cols = get_feature_columns()
        logger.info("Destinations: %d × %d features", len(dest_df), len(feature_cols))

        snap_id = save_feature_snapshot(db, feature_version=2, rows_count=len(dest_df), purpose="training")
        logger.info("Feature snapshot: %s", snap_id)

        logger.info("=== Phase 2: Load and featurise pairs ===")
        records = load_pairs(db, dest_df, feature_cols)

        n_feat = records[0]["features"].shape[0]
        from collections import Counter

        label_dist = Counter(r["label"] for r in records)
        logger.info("Pairs: %d  Features: %d  Labels: %s", len(records), n_feat, dict(sorted(label_dist.items())))

        logger.info("=== Phase 3: Train/test split by query ===")
        train_recs, test_recs = split_by_query(records, holdout=holdout)
        n_train_q = len({r["query_id"] for r in train_recs})
        n_test_q = len({r["query_id"] for r in test_recs})
        logger.info("Train: %d pairs / %d queries", len(train_recs), n_train_q)
        logger.info("Test:  %d pairs / %d queries", len(test_recs), n_test_q)

        logger.info("=== Phase 4: LightGBM LambdaRank ===")
        train_ds, _ = to_lgb_dataset(train_recs)
        val_ds, _ = to_lgb_dataset(test_recs, reference=train_ds)

        feature_names = [
            "u_budget_low",
            "u_budget_high",
            "u_budget_min_norm",
            "u_budget_max_norm",
            "u_budget_center",
            "u_budget_fit_tier",
            "u_trip_budget_fit",
            "u_duration_norm",
            "u_act_match",
            "u_top3_beach",
            "u_top3_culture",
            "u_top3_active",
            "u_top3_nature",
            "u_risk_norm",
            "u_safety_sensitive",
            "u_visa_strictness",
            "u_crowd_pref",
            "u_wants_coastal",
            "u_wants_mountain",
            "u_has_origin",
            "u_n_prefs",
            "u_month_norm",
            "u_month_sin",
            "u_month_cos",
            "u_climate_any",
            "u_crowd_fit",
            "u_climate_match",
            "u_origin_proximity",
        ] + feature_cols
        train_ds.set_feature_name(feature_names)
        val_ds.set_feature_name(feature_names)

        # LightGBM lambdarank NDCG at iter=1 is artificially inflated (pre-learning baseline).
        # We skip the first 20 iterations in early stopping to avoid choosing that false peak.
        # Real learning starts from iter~5 and converges around iter 80-150.
        eval_results: dict = {}
        callbacks = [
            lgb.log_evaluation(period=25),
            lgb.record_evaluation(eval_results),
        ]
        model = lgb.train(
            LGBM_PARAMS,
            train_ds,
            num_boost_round=N_ROUNDS,
            valid_sets=[val_ds],
            callbacks=callbacks,
        )

        # Manual best-iteration selection: skip first 10 rounds (artificially high NDCG)
        ndcg10_curve = eval_results.get("valid_0", {}).get("ndcg@10", [])
        if len(ndcg10_curve) > 10:
            best_iter_manual = int(np.argmax(ndcg10_curve[10:]) + 10) + 1
            logger.info(
                "Manual best_iter (skip first 10): %d  NDCG@10=%.4f  (iter1=%.4f)",
                best_iter_manual,
                ndcg10_curve[best_iter_manual - 1],
                ndcg10_curve[0],
            )
            # Re-train to that iteration
            model = lgb.train(
                LGBM_PARAMS,
                train_ds,
                num_boost_round=best_iter_manual,
            )
        else:
            best_iter_manual = model.num_trees()

        logger.info("=== Phase 5: Evaluate ===")
        X_test = np.stack([r["features"] for r in test_recs]).astype(np.float32)
        test_preds = np.asarray(model.predict(X_test), dtype=np.float64)

        ndcg5 = ndcg_at_k(test_recs, test_preds, k=5)
        ndcg10 = ndcg_at_k(test_recs, test_preds, k=ndcg_cutoff)
        logger.info("NDCG@5  = %.4f", ndcg5)
        logger.info("NDCG@10 = %.4f", ndcg10)

        if ndcg10 < 0.5:
            logger.warning("NDCG@10 %.4f < 0.5 threshold — below target quality", ndcg10)
        else:
            logger.info("NDCG@10 target met ✓")

        # Feature importance top-15
        imp = sorted(zip(feature_names, model.feature_importance("gain"), strict=False), key=lambda x: -x[1])[:15]
        logger.info("Top features by gain: %s", [(n, int(v)) for n, v in imp])

        logger.info("=== Phase 6: Save model ===")
        MODEL_SAVE_DIR.mkdir(parents=True, exist_ok=True)
        model_path = str(MODEL_SAVE_DIR / "ranker_ltr_v1.lgb")
        model.save_model(model_path)

        metrics = {
            "ndcg_at_5": round(ndcg5, 4),
            "ndcg_at_10": round(ndcg10, 4),
            "n_train_pairs": len(train_recs),
            "n_test_pairs": len(test_recs),
            "n_train_queries": n_train_q,
            "n_test_queries": n_test_q,
            "n_features": n_feat,
            "best_iteration": best_iter_manual,
            "n_estimators": int(model.num_trees()),
        }

        # Serialise artifact to bytes for persistent storage in DB (survives container restarts)
        import io

        artifact = {
            "model": model,
            "feature_cols": feature_cols,
            "feature_names": feature_names,
            "n_user_features": 28,
            "metrics": metrics,
        }
        buf = io.BytesIO()
        joblib.dump(artifact, buf)
        artifact_blob = buf.getvalue()
        logger.info("Artifact serialised: %.1f KB", len(artifact_blob) / 1024)

        joblib.dump(artifact, str(MODEL_SAVE_DIR / "ranker_ltr_v1.joblib"))

        model_id = register_model(db, model_path, metrics, artifact_blob)
        logger.info("Registered: id=%s", model_id)

        logger.info("=== Done: NDCG@5=%.4f  NDCG@10=%.4f  best_iter=%d ===", ndcg5, ndcg10, best_iter_manual)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--holdout", type=float, default=0.20)
    parser.add_argument("--ndcg-cutoff", type=int, default=10)
    args = parser.parse_args()
    main(holdout=args.holdout, ndcg_cutoff=args.ndcg_cutoff)
