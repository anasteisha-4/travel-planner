ACTIVITY_TYPE_MAP = {
    "beach": "act_beach",
    "culture": "act_culture",
    "adventure": "act_active",
    "active": "act_active",
    "nature": "act_nature",
    "food": "act_food",
    "shopping": "act_shopping",
    "nightlife": "act_nightlife",
    "family": "act_family",
    "romance": "act_romance",
    "wellness": "act_romance",
    "urban": "act_culture",
    "business": "act_business",
}

BUDGET_TIER_RANGES = {
    "budget": (0.0, 0.35),
    "mid": (0.25, 0.60),
    "premium": (0.45, 0.80),
    "luxury": (0.65, 1.0),
}


def _build_pair_features(
    profile_snapshot: dict,
    dest_row: Any,
    feature_cols: list[str],
    travel_month: int,
) -> np.ndarray:
    """28-dim user features + 39-dim destination features = 67 total.

    User features are RAW preferences (not pre-computed fits) so LightGBM
    must learn the user × dest interaction itself. Pre-computing season_fit,
    safety_fit, visa_fit as user features would allow LightGBM to trivially
    memorise labels → best_iter=1 (the original circular label problem).

    Dims 0-7:   budget encoding
    Dims 8-12:  activity preferences (raw, ranked)
    Dims 13-16: raw constraint preferences (risk, visa, crowd, n_prefs)
    Dims 17-19: climate, origin, month
    Dims 20-24: month cyclical + climate_any
    Dims 25-27: interaction features (crowd_fit, climate_match, origin_proximity)
    Dims 28-66: destination feature vector (39 dims)
    """
    # Budget encoding
    budget_tier = str(profile_snapshot.get("budget_tier", "mid"))
    b_low, b_high = BUDGET_TIER_RANGES.get(budget_tier, (0.25, 0.60))
    budget_min_norm = float(profile_snapshot.get("budget_min_usd", 800)) / 20000.0
    budget_max_norm = float(profile_snapshot.get("budget_max_usd", 2000)) / 20000.0
    cost_index = float(dest_row.get("cost_index", 0.5))
    cost_mid = (b_low + b_high) / 2.0
    budget_fit = 1.0 - max(0.0, min(1.0, abs(cost_index - cost_mid) / 0.5))

    # Activity preferences — top-5 weighted match (raw interaction signal)
    vacation_prefs: list[str] = profile_snapshot.get("vacation_preferences_ranked") or []
    act_match = 0.0
    w_total = 0.0
    for rank, act in enumerate(vacation_prefs[:5], start=1):
        col = ACTIVITY_TYPE_MAP.get(act)
        if col and col in dest_row.index:
            w = 6 - rank
            act_match += w * float(dest_row[col])
            w_total += w
    act_match_norm = act_match / w_total if w_total > 0 else 0.0

    # Top-3 activity preference one-hot (which activities user wants)
    top3_beach = float(any(ACTIVITY_TYPE_MAP.get(a) == "act_beach" for a in vacation_prefs[:3]))
    top3_culture = float(any(ACTIVITY_TYPE_MAP.get(a) == "act_culture" for a in vacation_prefs[:3]))
    top3_active = float(any(ACTIVITY_TYPE_MAP.get(a) == "act_active" for a in vacation_prefs[:3]))
    top3_nature = float(any(ACTIVITY_TYPE_MAP.get(a) == "act_nature" for a in vacation_prefs[:3]))

    # Raw constraint preferences (LightGBM learns interaction with dest features)
    risk_tolerance = int(profile_snapshot.get("risk_tolerance", 3))
    risk_norm = float(risk_tolerance) / 5.0
    is_safety_sensitive = float(risk_tolerance <= 2)

    visa_tolerance = str(profile_snapshot.get("visa_tolerance", "any_visa"))
    visa_strictness = {"visa_free_only": 1.0, "evisa_ok": 0.5, "any_visa": 0.0}.get(visa_tolerance, 0.0)

    crowd_pref = float(profile_snapshot.get("crowd_preference", 3)) / 5.0
    n_prefs = float(len(vacation_prefs))

    # Climate preference encoding
    climate_prefs: list[str] = profile_snapshot.get("climate_preferences") or ["any"]
    wants_coastal = float(any(p in climate_prefs for p in ("tropical_warm", "mediterranean")))
    wants_mountain = float("cold_snow" in climate_prefs)
    climate_any = float("any" in climate_prefs)

    # Origin and month
    origin_lat = profile_snapshot.get("origin_lat")
    origin_lng = profile_snapshot.get("origin_lng")
    has_origin = float(origin_lat is not None)
    month_norm = float(travel_month) / 12.0
    # Month sine/cosine encoding (cyclical — Jan and Dec are adjacent)
    month_sin = math.sin(2 * math.pi * travel_month / 12)
    month_cos = math.cos(2 * math.pi * travel_month / 12)

    # Budget fit vs dest cost (matches independent_quality_score component 2)
    avg_daily = float(dest_row.get("avg_daily_cost_usd", 80.0))
    budget_min_usd = float(profile_snapshot.get("budget_min_usd") or 200)
    budget_max_usd = float(profile_snapshot.get("budget_max_usd") or 2000)
    duration_days = int(profile_snapshot.get("typical_duration_days") or 10)
    trip_cost = avg_daily * duration_days
    if budget_min_usd <= trip_cost <= budget_max_usd:
        trip_budget_fit = 1.0
    elif trip_cost < budget_min_usd:
        trip_budget_fit = max(0.3, 1.0 - (budget_min_usd - trip_cost) / max(budget_min_usd, 1) * 0.5)
    else:
        trip_budget_fit = max(0.0, 1.0 - (trip_cost - budget_max_usd) / max(budget_max_usd, 1))

    # Dim 25: crowd_fit — how well dest crowd_index matches user crowd_preference
    crowd_dest = float(dest_row.get("crowd_index_avg", 0.5))
    crowd_fit = 1.0 - abs(crowd_pref - crowd_dest)

    # Dim 26: climate_match — intersection of climate_prefs with dest attributes
    is_coastal = float(dest_row.get("is_coastal", 0))
    has_mountains = float(dest_row.get("has_mountains", 0))
    if "any" in climate_prefs:
        climate_match = 0.5
    else:
        hits = sum(
            [
                float(("tropical_warm" in climate_prefs or "mediterranean" in climate_prefs) and is_coastal > 0),
                float("cold_snow" in climate_prefs and has_mountains > 0),
                float("dry_desert" in climate_prefs and float(dest_row.get("safety_score", 0.5)) > 0.4),
            ]
        )
        climate_match = min(1.0, hits * 0.5)

    # Dim 27: origin_proximity — connectivity_score as accessibility proxy
    # (haversine requires origin_lng which is now included in profile snapshot)
    if origin_lat is not None and origin_lng is not None:
        proximity = float(dest_row.get("connectivity_score", 0.5))
    else:
        proximity = 0.5  # unknown origin → neutral

    user_vec = np.array(
        [
            b_low,  # 0  budget band low (tier)
            b_high,  # 1  budget band high (tier)
            budget_min_norm,  # 2  budget_min_usd normalised
            budget_max_norm,  # 3  budget_max_usd normalised
            cost_mid,  # 4  budget center (tier)
            budget_fit,  # 5  cost_index vs budget tier
            trip_budget_fit,  # 6  trip_cost (daily × days) vs budget range ← KEY interaction
            float(duration_days) / 45.0,  # 7  trip duration normalised
            act_match_norm,  # 8  weighted activity match (all 5 prefs)
            top3_beach,  # 9  wants beach (top-3 pref)
            top3_culture,  # 10 wants culture (top-3 pref)
            top3_active,  # 11 wants active/adventure (top-3 pref)
            top3_nature,  # 12 wants nature (top-3 pref)
            risk_norm,  # 13 risk tolerance normalised
            is_safety_sensitive,  # 14 risk <= 2
            visa_strictness,  # 15 visa strictness (0=any, 0.5=evisa, 1.0=free_only)
            crowd_pref,  # 16 crowd preference normalised
            wants_coastal,  # 17 prefers coastal/warm climate
            wants_mountain,  # 18 prefers cold/snow/mountain
            has_origin,  # 19 has origin city
            n_prefs,  # 20 number of activity preferences
            month_norm,  # 21 travel month (linear)
            month_sin,  # 22 travel month (sine — cyclical)
            month_cos,  # 23 travel month (cosine — cyclical)
            climate_any,  # 24 climate = any (flexible traveller)
            crowd_fit,  # 25 crowd_index vs crowd_preference (interaction)
            climate_match,  # 26 climate_prefs × is_coastal/has_mountains (interaction)
            proximity,  # 27 origin → dest accessibility via connectivity_score
        ],
        dtype=np.float32,
    )

    dest_vec = dest_row[feature_cols].values.astype(np.float32)
    return np.concatenate([user_vec, dest_vec])


