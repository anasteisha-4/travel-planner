MODEL_SAVE_DIR = Path("/tmp/ml_models")

LGBM_PARAMS = {
    "objective": "lambdarank",
    "metric": "ndcg",
    "ndcg_eval_at": [5, 10],
    "learning_rate": 0.05,
    "num_leaves": 63,
    "max_depth": 8,
    "min_data_in_leaf": 20,
    "feature_fraction": 0.8,
    "bagging_fraction": 0.8,
    "bagging_freq": 5,
    "lambda_l1": 0.1,
    "lambda_l2": 0.5,
    "label_gain": [0, 1, 3, 7],
    "verbose": -1,
    "n_jobs": -1,
}

N_ROUNDS = 500
EARLY_STOPPING = 40


